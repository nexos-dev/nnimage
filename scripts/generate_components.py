def outputInclude(slots: list[Slot]) -> str:
    lines = [COMMENTHEADER]
    includedHeaders = []
    for slot in slots:
        for component in slot.components:
            header = component.vals["HEADER"]
            if header not in includedHeaders:
                includedHeaders.append(header)
                lines.append(f'#include "{header}"')

    lines.append("")
    return "\n".join(lines)

SLOTPROPS = ["ENUMNAME", "BASECLASS", "NAMEREGISTRY", "FACTORYREGISTRY", "COMPTYPE"]
COMPPROPS = ["NAME", "SLOT", "CLASS", "HEADER"]

def readSlots(compsDir: Path) -> list[Slot]:
    slotList = []
    # Start by reading all .comp files in the slot directory
    slots = sorted((compsDir / "slots").glob("*.comp"))
    for slot in slots:
        vals = readComponentFile(slot)
        slotObj = Slot({}, [])
        # Check all the properties
        for prop in SLOTPROPS:
            requiredValue(vals, prop, slot)
            slotObj.vals[prop] = vals[prop]
        # Now get the components
        slotDir = compsDir / "slots" / slot.stem
        comps = slotDir.glob("*.comp")

        if not comps:
            raise ValueError(f"No found component files for slot {slot.stem}")
        for comp in comps:
            compVals = readComponentFile(comp)
            compObj = Component({})

            for prop in COMPPROPS:
                requiredValue(compVals, prop, comp)
                compObj.vals[prop] = compVals[prop]
                if prop == "SLOT":
                    slotObj.components.append(compObj)
        slotList.append(slotObj)
    return slotList

