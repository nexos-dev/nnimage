import argparse
from pathlib import Path
from dataclasses import dataclass

COMMENTHEADER = "/* This file is auto-generated by generate_components.py. Do not edit manually. */"

# A struct representing a component
@dataclass
class Component:
    vals: dict[str, str]

# A struct representing a slot
@dataclass
class Slot:
    vals: dict[str, str]
    components: list[Component]

def componentTypeName(name: str) -> str:
    return name[:1].upper() + name[1:]


def readComponentFile(path: Path) -> dict[str, str]:
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, separator, value = line.partition("=")
        if not separator:
            raise ValueError(f'Component file "{path}" is missing a seperator')
        values[name] = value
    return values


def requiredValue(values: dict[str, str], name: str, path: Path) -> str:
    value = values.get(name, "")
    if not value:
        raise ValueError(f'Component file "{path}" is missing {name}')
    return value


def outputTypes(slots: list[Slot]) -> str:
    lines = [
        COMMENTHEADER,
        "#ifndef COMPTYPES_H",
        "#define COMPTYPES_H",
    ]

    for slot in slots:
        lines.extend(["", f"enum class {slot.vals['ENUMNAME']} {{"])
        for component in slot.components:
            lines.append(f"    {componentTypeName(component.vals['NAME'])},")
        lines.extend(["    Max", "};"])

    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


